// Helpers
// ---------------------------------------------------------------------------

/// Load model from safetensors weights, returning `None` if weights absent.
fn load_model(audio_t: usize) -> Option<(HTDemucs, PipelineCache)> {
    let weights_path = project_root().join("models/demucs/htdemucs_temporal.safetensors");
    if !weights_path.exists() {
        eprintln!(
            "SKIP: Demucs weights not found at {}",
            weights_path.display()
        );
        return None;
    }

    let backend = MetalBackend::init().expect("Metal backend required");
    let ctx = backend.context().clone();

    // SAFETY: weight file is a valid safetensors file, context is initialized,
    // file outlives the WeightMap (dropped in this scope).
    let wm = unsafe { WeightMap::load(&weights_path, &ctx).expect("load safetensors") };
    assert!(
        wm.tensor_count() >= 280,
        "expected >=280 tensors in temporal branch, got {}",
        wm.tensor_count(),
    );

    let weights = HTDemucsWeights::from_weight_map(&wm).expect("weight loading");
    let model = HTDemucs::new(weights, audio_t).expect("model construction");
    let cache = PipelineCache::new(ctx);
    Some((model, cache))
}

/// Assert output is the expected length and all finite.
fn assert_output_valid(out: &[f32], expected_len: usize, label: &str) {
    assert_eq!(out.len(), expected_len, "{label}: length mismatch");
    let non_finite = out.iter().filter(|v| !v.is_finite()).count();
    assert_eq!(non_finite, 0, "{label}: {non_finite} non-finite values");
    eprintln!(
        "{label}: len={}, range=[{:.6}, {:.6}]",
        out.len(),
        out.iter().copied().reduce(f32::min).unwrap_or(0.0),
        out.iter().copied().reduce(f32::max).unwrap_or(0.0),
    );
}

/// Generate deterministic pseudo-random noise of given length.
fn deterministic_noise(len: usize) -> Vec<f32> {
    let mut buf = vec![0.0f32; len];
    let mut rng_state: u64 = 42;
    for v in &mut buf {
        rng_state ^= rng_state << 13;
        rng_state ^= rng_state >> 7;
        rng_state ^= rng_state << 17;
        *v = ((rng_state as f32) / (u64::MAX as f32)) * 0.2 - 0.1;
    }
    buf
}

