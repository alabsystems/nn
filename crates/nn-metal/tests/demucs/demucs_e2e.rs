//! End-to-end HTDemucs test with real weights.
//!
//! Loads real model weights from `models/demucs/htdemucs_temporal.safetensors`
//! and runs the full temporal branch forward pass.
//!
//! When weights are absent the test prints a skip message and returns Ok
//! (graceful skip via early return, not test-level skip attributes).
//!
//! Part of #779 — Milestone 1, AC3 (E2E test with real weights).

use std::path::Path;

use nn_metal::{HTDemucs, HTDemucsWeights, MetalBackend, PipelineCache, WeightMap};
use nn_reftest::{compare_tensors, ComparisonConfig, NamedTensor};

/// Project root (two levels up from `crates/nn-metal/`).
fn project_root() -> std::path::PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|p| p.parent())
        .expect("project root")
        .to_path_buf()
}

