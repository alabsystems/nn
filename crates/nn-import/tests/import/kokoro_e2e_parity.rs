//! Kokoro converter E2E parity tests (#4189).
//!
//! Validates that the `nn-import` auto-converter pipeline produces a Kokoro
//! model numerically equivalent to the hand-built `KokoroModel`:
//!
//! 1. **Mini decoder import** (always runs): Parses `kokoro_decoder_mini.json`,
//!    validates graph structure. On Metal: builds graph with synthetic weights,
//!    compiles, executes, and verifies finite output.
//!
//! 2. **Real-weights import** (gated on `KOKORO_WEIGHTS`): Loads real Kokoro
//!    weights from safetensors, parses the decoder fixture, builds the imported
//!    graph, and validates op mapping coverage.
//!
//! 3. **Converter vs hand-built shape parity** (gated on `KOKORO_WEIGHTS`):
//!    Loads real weights into both the hand-built `KokoroModel` (via VarBuilder)
//!    and the auto-converter (via `import_mini_fixture`), then compares graph
//!    structure and output node counts.
//!
//! Part of #4189 (Kokoro converter E2E parity test).

use std::collections::HashMap;
use std::path::{Path, PathBuf};

use nn_core::dyn_tensor::trace::TraceOp;
use nn_import::{build_graph, build_weight_map, parse_exported_program, ImportedGraph, InputSpec};

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

fn test_data_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("test_data")
}

/// Returns the KOKORO_WEIGHTS env var path, or None if unset/missing.
fn kokoro_weights_path() -> Option<PathBuf> {
    let path = std::env::var("KOKORO_WEIGHTS").ok()?;
    let p = PathBuf::from(&path);
    if p.exists() {
        Some(p)
    } else {
        eprintln!("SKIP: KOKORO_WEIGHTS={path} does not exist");
        None
    }
}

/// Parse a mini fixture JSON and build the computation graph with uniform
/// synthetic weights (all 0.01) matching declared shapes.
fn import_mini_fixture(json_name: &str) -> ImportedGraph {
    import_mini_fixture_with_fill(json_name, |_fqn, n| vec![0.01f32; n])
}

/// Parse a mini fixture JSON and build the computation graph with custom
/// weight values generated by the `fill` closure.
///
/// `fill(fqn, numel)` returns the weight data for a parameter with the
/// given fully-qualified name and element count.
fn import_mini_fixture_with_fill(
    json_name: &str,
    fill: impl Fn(&str, usize) -> Vec<f32>,
) -> ImportedGraph {
    let json_path = test_data_dir().join(json_name);
    let json_bytes =
        std::fs::read(&json_path).unwrap_or_else(|e| panic!("read {}: {e}", json_path.display()));
    let program =
        parse_exported_program(&json_bytes).unwrap_or_else(|e| panic!("parse {json_name}: {e:?}"));

    let mut weight_data: HashMap<String, (Vec<f32>, Vec<usize>)> = HashMap::new();
    for spec in &program.graph_module.signature.input_specs {
        if let InputSpec::Parameter(p) = spec {
            let fqn = &p.parameter.parameter_name;
            let name = &p.parameter.arg.name;
            if let Some(meta) = program.graph_module.graph.tensor_values.get(name) {
                if let Some(shape) = meta.concrete_shape() {
                    let n: usize = shape.iter().copied().product();
                    weight_data.insert(fqn.clone(), (fill(fqn, n), shape));
                }
            }
        }
    }

    let weight_map = build_weight_map(&program.graph_module.signature.input_specs, &weight_data);
    build_graph(&program, &weight_map)
        .unwrap_or_else(|e| panic!("build_graph for {json_name}: {e:?}"))
}

/// Deterministic pseudo-random f32 generator (LCG) for reproducible varied weights.
/// Returns values in [-scale, +scale] centered around 0.
fn deterministic_varied_weights(seed: u64, numel: usize, scale: f32) -> Vec<f32> {
    let mut state = seed;
    (0..numel)
        .map(|_| {
            // LCG: state = state * 6364136223846793005 + 1442695040888963407
            state = state
                .wrapping_mul(6364136223846793005)
                .wrapping_add(1442695040888963407);
            // Map to [-scale, scale]
            let normalized = ((state >> 33) as f32) / (u32::MAX as f32 / 2.0) - 1.0;
            normalized * scale
        })
        .collect()
}

/// Cosine similarity between two f32 slices.
fn cosine_similarity(a: &[f32], b: &[f32]) -> f64 {
    assert_eq!(a.len(), b.len(), "cosine_similarity: length mismatch");
    let mut dot = 0.0f64;
    let mut norm_a = 0.0f64;
    let mut norm_b = 0.0f64;
    for (&x, &y) in a.iter().zip(b.iter()) {
        let x = f64::from(x);
        let y = f64::from(y);
        dot += x * y;
        norm_a += x * x;
        norm_b += y * y;
    }
    let denom = norm_a.sqrt() * norm_b.sqrt();
    if denom < 1e-12 {
        0.0
    } else {
        dot / denom
    }
}

/// Maximum absolute difference between two f32 slices.
fn max_abs_diff(a: &[f32], b: &[f32]) -> f32 {
    assert_eq!(a.len(), b.len(), "max_abs_diff: length mismatch");
    a.iter()
        .zip(b.iter())
        .map(|(x, y)| (x - y).abs())
        .fold(0.0f32, f32::max)
}

