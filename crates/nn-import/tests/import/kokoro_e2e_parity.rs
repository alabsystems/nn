/// Parses the Kokoro decoder mini fixture and validates the graph has the
/// expected structure: Conv1d ops, user inputs, and correct output names.
#[test]
fn test_kokoro_e2e_mini_decoder_parse_and_validate() {
    let json_path = test_data_dir().join("kokoro_decoder_mini.json");
    if !json_path.exists() {
        eprintln!(
            "SKIP: kokoro_decoder_mini.json not found at {}",
            json_path.display()
        );
        return;
    }

    // Step 1: Parse the exported program.
    let json_bytes = std::fs::read(&json_path).unwrap();
    let program =
        parse_exported_program(&json_bytes).expect("parse kokoro_decoder_mini.json must succeed");

    // Validate signature: should have user inputs and parameters.
    let user_input_count = program
        .graph_module
        .signature
        .input_specs
        .iter()
        .filter(|s| matches!(s, InputSpec::UserInput(_)))
        .count();
    assert!(
        user_input_count >= 1,
        "decoder mini should have >= 1 user input, got {user_input_count}"
    );

    let param_count = program
        .graph_module
        .signature
        .input_specs
        .iter()
        .filter(|s| matches!(s, InputSpec::Parameter(_)))
        .count();
    assert!(
        param_count >= 2,
        "decoder mini should have >= 2 parameters, got {param_count}"
    );

    eprintln!(
        "Parse: {} user inputs, {} parameters, {} graph nodes",
        user_input_count,
        param_count,
        program.graph_module.graph.nodes.len()
    );

    // Step 2: Build the imported graph with synthetic weights.
    let imported = import_mini_fixture("kokoro_decoder_mini.json");

    assert!(
        imported.num_user_inputs >= 1,
        "decoder should have >= 1 user input, got {}",
        imported.num_user_inputs
    );
    assert!(
        !imported.output_names.is_empty(),
        "decoder should have outputs"
    );

    // Step 3: Verify expected op pattern: Conv1d ops for decoder.
    let nodes = imported.graph.nodes();
    let conv_count = nodes
        .iter()
        .filter(|n| matches!(n.op(), TraceOp::Conv1d { .. }))
        .count();
    assert!(
        conv_count >= 1,
        "decoder should have >= 1 Conv1d op, got {conv_count}"
    );

    // Count all op types for coverage reporting.
    let total_ops = nodes.len();
    let instance_norm_count = nodes
        .iter()
        .filter(|n| matches!(n.op(), TraceOp::InstanceNorm { .. }))
        .count();

    eprintln!(
        "Graph: {} total nodes, {} Conv1d, {} InstanceNorm, {} user inputs, {} outputs -- PASSED",
        total_ops,
        conv_count,
        instance_norm_count,
        imported.num_user_inputs,
        imported.output_names.len()
    );
}

/// On Metal: compile the mini decoder with synthetic weights and execute with
/// zeros input, verifying the output is finite.
#[test]
#[cfg(all(feature = "metal", target_os = "macos"))]
fn test_kokoro_e2e_mini_decoder_compile_and_execute() {
    use nn_core::{DType, Device};

    let json_path = test_data_dir().join("kokoro_decoder_mini.json");
    if !json_path.exists() {
        eprintln!(
            "SKIP: kokoro_decoder_mini.json not found at {}",
            json_path.display()
        );
        return;
    }

    let imported = import_mini_fixture("kokoro_decoder_mini.json");

    let _ = nn_metal::MetalBackend::init();
    nn_metal::register_metal_dyn_backend();
    let cache = nn_metal::PipelineCache::new(
        nn_metal::MetalContext::new().expect("Metal device required"),
    );

    // Compile via trace compilation.
    let plan = nn_dsl::trace_compile::compile_trace_to_plan_with_fusion(&imported.graph)
        .unwrap_or_else(|e| panic!("decoder mini trace compilation failed: {e:?}"));
    let compiled =
        nn_metal::compiled_model::CompiledModel::from_plan(&plan, &imported.graph, &cache)
            .unwrap_or_else(|e| panic!("decoder mini from_plan failed: {e:?}"));

    assert!(
        compiled.num_steps() > 0,
        "should have > 0 compiled steps, got {}",
        compiled.num_steps()
    );
    assert!(
        compiled.num_dispatches() > 0,
        "should have > 0 dispatches, got {}",
        compiled.num_dispatches()
    );

    // Execute with synthetic input matching decoder mini shape: [1, 8, 16].
    let input_data: Vec<f32> = (0..128).map(|i| (i as f32) * 0.01).collect();
    let input_cpu = nn_core::DynTensor::from_vec(input_data, &[1, 8, 16], &Device::Cpu).unwrap();
    let input_gpu = input_cpu.to_device(&Device::metal()).unwrap();

    let output = compiled
        .execute_dyn(&cache, &[&input_gpu])
        .expect("GPU execution must succeed for decoder mini");

    assert_eq!(output.dtype(), DType::F32);

    // Verify output is finite and non-trivial.
    let output_cpu = output.to_device(&Device::Cpu).unwrap();
    let vals = output_cpu.to_flat_vec::<f32>().unwrap();
    assert!(
        !vals.is_empty(),
        "output should have non-zero element count"
    );

    let all_finite = vals.iter().all(|v| v.is_finite());
    assert!(all_finite, "GPU output contains non-finite values");

    let energy: f64 = vals.iter().map(|v| f64::from(*v).powi(2)).sum();
    assert!(
        energy > 1e-10,
        "GPU output is near-zero (energy={energy:.6e})"
    );

    eprintln!(
        "Compile+Execute: shape={:?}, {} elements, energy={:.4e}, \
         {} steps, {} dispatches -- PASSED",
        output.dims(),
        vals.len(),
        energy,
        compiled.num_steps(),
        compiled.num_dispatches(),
    );
}

// ===========================================================================
// Test A2: Numerical parity — auto-converted GPU vs hand-built CPU (Metal)
// ===========================================================================

/// Numerical parity test: auto-converted mini decoder executed on GPU vs the
/// same computation replicated on CPU using DynTensor ops.
///
/// The mini decoder fixture implements:
///   x → Conv1d(8→16, k=3, pad=1) → InstanceNorm(eps=1e-5) → LeakyReLU(0.2)
///     → Conv1d(16→16, k=3, pad=1) → Add(residual=norm_0) → split at ch=8:
///       [:8] → exp → magnitude
///       [8:] → sin → phase
///     → cat([magnitude, phase], dim=1) → output [1, 16, 16]
///
/// Both paths use the same synthetic weights (all 0.01) and identical input.
/// Since the mini fixture is a synthetic subgraph (not a real Kokoro decoder
/// submodule), this tests the auto-converter's numerical fidelity against a
/// hand-built CPU reference for the same graph — not against KokoroModel itself.
///
/// With real production weights (KOKORO_WEIGHTS), true end-to-end parity
/// would require running the full 5-segment Kokoro pipeline, which is blocked
/// on `length_regulate` CPU readback (see `test_converter_full_kokoro_parity_gap_documented`).
#[test]
#[cfg(all(feature = "metal", target_os = "macos"))]
fn test_kokoro_e2e_mini_decoder_numerical_parity() {
    use nn_core::layers::{InstanceNorm, Module};
    use nn_core::Device;

    let json_path = test_data_dir().join("kokoro_decoder_mini.json");
    if !json_path.exists() {
        eprintln!(
            "SKIP: kokoro_decoder_mini.json not found at {}",
            json_path.display()
        );
        return;
    }

    // --- Auto-converted GPU path ---

    let imported = import_mini_fixture("kokoro_decoder_mini.json");

    let _ = nn_metal::MetalBackend::init();
    nn_metal::register_metal_dyn_backend();
    let cache = nn_metal::PipelineCache::new(
        nn_metal::MetalContext::new().expect("Metal device required"),
    );

    let plan = nn_dsl::trace_compile::compile_trace_to_plan_with_fusion(&imported.graph)
        .unwrap_or_else(|e| panic!("trace compilation failed: {e:?}"));
    let compiled =
        nn_metal::compiled_model::CompiledModel::from_plan(&plan, &imported.graph, &cache)
            .unwrap_or_else(|e| panic!("from_plan failed: {e:?}"));

    // Same input as other tests: [1, 8, 16].
    let input_data: Vec<f32> = (0..128).map(|i| (i as f32) * 0.01).collect();
    let input_cpu =
        nn_core::DynTensor::from_vec(input_data, &[1, 8, 16], &Device::Cpu).unwrap();
    let input_gpu = input_cpu.to_device(&Device::metal()).unwrap();

    let gpu_output = compiled
        .execute_dyn(&cache, &[&input_gpu])
        .expect("GPU execution must succeed");
    let gpu_output_cpu = gpu_output.to_device(&Device::Cpu).unwrap();
    let gpu_vals = gpu_output_cpu.to_flat_vec::<f32>().unwrap();

    // --- Hand-built CPU path (replicates mini decoder graph exactly) ---

    // Synthetic weights matching import_mini_fixture: all 0.01.
    let conv1_w =
        nn_core::DynTensor::from_vec(vec![0.01f32; 16 * 8 * 3], &[16, 8, 3], &Device::Cpu)
            .unwrap();
    let conv1_b = nn_core::DynTensor::from_vec(vec![0.01f32; 16], &[16], &Device::Cpu).unwrap();
    let conv2_w =
        nn_core::DynTensor::from_vec(vec![0.01f32; 16 * 16 * 3], &[16, 16, 3], &Device::Cpu)
            .unwrap();
    let conv2_b = nn_core::DynTensor::from_vec(vec![0.01f32; 16], &[16], &Device::Cpu).unwrap();

    // Step 1: Conv1d(x, conv1_w) + conv1_b → conv_0 [1, 16, 16]
    let conv_0 = input_cpu
        .conv1d(
            &conv1_w, /*padding=*/ 1, /*stride=*/ 1, /*dilation=*/ 1,
            /*groups=*/ 1,
        )
        .unwrap();
    // Add bias: reshape [16] → [1, 16, 1] for broadcast.
    let bias1 = conv1_b.reshape([1, 16, 1]).unwrap();
    let conv_0 = conv_0.broadcast_add(&bias1).unwrap();

    // Step 2: InstanceNorm(conv_0, eps=1e-5) → norm_0 [1, 16, 16]
    let inst_norm = InstanceNorm::new(1e-5).unwrap();
    let norm_0 = inst_norm.forward(&conv_0).unwrap();

    // Step 3: LeakyReLU(norm_0, negative_slope=0.2) → lrelu [1, 16, 16]
    let lrelu = norm_0.leaky_relu(0.2).unwrap();

    // Step 4: Conv1d(lrelu, conv2_w) + conv2_b → conv_1 [1, 16, 16]
    let conv_1 = lrelu
        .conv1d(
            &conv2_w, /*padding=*/ 1, /*stride=*/ 1, /*dilation=*/ 1,
            /*groups=*/ 1,
        )
        .unwrap();
    let bias2 = conv2_b.reshape([1, 16, 1]).unwrap();
    let conv_1 = conv_1.broadcast_add(&bias2).unwrap();

    // Step 5: residual = norm_0 + conv_1 [1, 16, 16]
    let residual = norm_0.add(&conv_1).unwrap();

    // Step 6: log_mag = residual[:, :8, :], magnitude = exp(log_mag) [1, 8, 16]
    let log_mag = residual.narrow(1, 0, 8).unwrap();
    let magnitude = log_mag.exp().unwrap();

    // Step 7: phase_raw = residual[:, 8:, :], phase = sin(phase_raw) [1, 8, 16]
    let phase_raw = residual.narrow(1, 8, 8).unwrap();
    let phase = phase_raw.sin().unwrap();

    // Step 8: output = cat([magnitude, phase], dim=1) → [1, 16, 16]
    let cpu_output = nn_core::DynTensor::cat(&[&magnitude, &phase], 1).unwrap();

    // --- Numerical comparison ---

    let cpu_vals = cpu_output.to_flat_vec::<f32>().unwrap();

    assert_eq!(
        gpu_vals.len(),
        cpu_vals.len(),
        "output length mismatch: GPU={} vs CPU={}",
        gpu_vals.len(),
        cpu_vals.len()
    );

    // Both outputs must be finite and non-trivial.
    let gpu_all_finite = gpu_vals.iter().all(|v| v.is_finite());
    let cpu_all_finite = cpu_vals.iter().all(|v| v.is_finite());
    assert!(gpu_all_finite, "GPU output contains non-finite values");
    assert!(cpu_all_finite, "CPU output contains non-finite values");

    let gpu_energy: f64 = gpu_vals.iter().map(|v| f64::from(*v).powi(2)).sum();
    let cpu_energy: f64 = cpu_vals.iter().map(|v| f64::from(*v).powi(2)).sum();
    assert!(
        gpu_energy > 1e-10,
        "GPU output is near-zero (energy={gpu_energy:.6e})"
    );
    assert!(
        cpu_energy > 1e-10,
        "CPU output is near-zero (energy={cpu_energy:.6e})"
    );

    let cos_sim = cosine_similarity(&gpu_vals, &cpu_vals);
    let max_diff = max_abs_diff(&gpu_vals, &cpu_vals);

    eprintln!("Numerical parity: cosine_similarity={cos_sim:.6}, max_abs_diff={max_diff:.6e}");
    eprintln!(
        "  GPU: {} elements, energy={gpu_energy:.4e}, shape={:?}",
        gpu_vals.len(),
        gpu_output.dims()
    );
    eprintln!(
        "  CPU: {} elements, energy={cpu_energy:.4e}, shape={:?}",
        cpu_vals.len(),
        cpu_output.dims()
    );

    // Assertion thresholds: GPU and CPU instance_norm may use different
    // accumulator precision (f64 CPU vs f32 GPU), so allow some tolerance.
    assert!(
        cos_sim > 0.99,
        "cosine similarity {cos_sim:.6} below 0.99 threshold \
         (auto-converted GPU vs hand-built CPU)"
    );
    assert!(
        max_diff < 0.5,
        "max absolute difference {max_diff:.6e} exceeds 0.5 threshold \
         (auto-converted GPU vs hand-built CPU)"
    );

    eprintln!(
        "Mini decoder numerical parity: cos={cos_sim:.6}, max_diff={max_diff:.6e}, \
         {} steps, {} dispatches -- PASSED",
        compiled.num_steps(),
        compiled.num_dispatches(),
    );
}

// ===========================================================================
// Test A3: Varied-weights numerical parity — diverse magnitudes (Metal)
// ===========================================================================

/// Numerical parity test with varied (non-uniform) synthetic weights.
///
/// Uniform weights (all 0.01) may mask numerical issues because all channels
/// have identical activation magnitudes. This test uses deterministic
/// pseudo-random weights with diverse magnitudes (like real production
/// weights), which exercises:
///   - InstanceNorm with non-uniform channel statistics
///   - Conv1d with mixed-sign filter coefficients
///   - LeakyReLU with both positive and negative activations
///   - exp/sin on values with realistic spread
///
/// Both auto-converted GPU and hand-built CPU use identical varied weights.
/// Thresholds: cosine > 0.99, max_abs_diff < 0.5.
#[test]
#[cfg(all(feature = "metal", target_os = "macos"))]
fn test_kokoro_e2e_mini_decoder_varied_weights_parity() {
    use nn_core::layers::{InstanceNorm, Module};
    use nn_core::Device;

    let json_path = test_data_dir().join("kokoro_decoder_mini.json");
    if !json_path.exists() {
        eprintln!(
            "SKIP: kokoro_decoder_mini.json not found at {}",
            json_path.display()
        );
        return;
    }

    // Use a deterministic seed for reproducible varied weights.
    let seed = 42u64;
    let scale = 0.1f32; // Moderate scale to avoid InstanceNorm instability.

    // --- Auto-converted GPU path with varied weights ---

    let imported = import_mini_fixture_with_fill("kokoro_decoder_mini.json", |_fqn, n| {
        deterministic_varied_weights(seed, n, scale)
    });

    let _ = nn_metal::MetalBackend::init();
    nn_metal::register_metal_dyn_backend();
    let cache = nn_metal::PipelineCache::new(
        nn_metal::MetalContext::new().expect("Metal device required"),
    );

    let plan = nn_dsl::trace_compile::compile_trace_to_plan_with_fusion(&imported.graph)
        .unwrap_or_else(|e| panic!("trace compilation failed: {e:?}"));
    let compiled =
        nn_metal::compiled_model::CompiledModel::from_plan(&plan, &imported.graph, &cache)
            .unwrap_or_else(|e| panic!("from_plan failed: {e:?}"));

    // Varied input to exercise different activation ranges.
    let input_data: Vec<f32> = (0..128).map(|i| ((i as f32) - 64.0) * 0.02).collect();
    let input_cpu =
        nn_core::DynTensor::from_vec(input_data, &[1, 8, 16], &Device::Cpu).unwrap();
    let input_gpu = input_cpu.to_device(&Device::metal()).unwrap();

    let gpu_output = compiled
        .execute_dyn(&cache, &[&input_gpu])
        .expect("GPU execution must succeed");
    let gpu_output_cpu = gpu_output.to_device(&Device::Cpu).unwrap();
    let gpu_vals = gpu_output_cpu.to_flat_vec::<f32>().unwrap();

    // --- Hand-built CPU path with the SAME varied weights ---

    // Generate the same varied weights in the same order as the fixture.
    // The fixture processes parameters in input_specs order:
    //   conv1.weight [16,8,3], conv1.bias [16], conv2.weight [16,16,3], conv2.bias [16]
    let conv1_w_data = deterministic_varied_weights(seed, 16 * 8 * 3, scale);
    let conv1_b_data = deterministic_varied_weights(seed, 16, scale);
    let conv2_w_data = deterministic_varied_weights(seed, 16 * 16 * 3, scale);
    let conv2_b_data = deterministic_varied_weights(seed, 16, scale);

    let conv1_w = nn_core::DynTensor::from_vec(conv1_w_data, &[16, 8, 3], &Device::Cpu).unwrap();
    let conv1_b = nn_core::DynTensor::from_vec(conv1_b_data, &[16], &Device::Cpu).unwrap();
    let conv2_w = nn_core::DynTensor::from_vec(conv2_w_data, &[16, 16, 3], &Device::Cpu).unwrap();
    let conv2_b = nn_core::DynTensor::from_vec(conv2_b_data, &[16], &Device::Cpu).unwrap();

    // Replicate the mini decoder graph: Conv1d -> InstanceNorm -> LeakyReLU
    // -> Conv1d -> Add(residual) -> split -> exp/sin -> cat.
    let conv_0 = input_cpu.conv1d(&conv1_w, 1, 1, 1, 1).unwrap();
    let bias1 = conv1_b.reshape([1, 16, 1]).unwrap();
    let conv_0 = conv_0.broadcast_add(&bias1).unwrap();

    let inst_norm = InstanceNorm::new(1e-5).unwrap();
    let norm_0 = inst_norm.forward(&conv_0).unwrap();

    let lrelu = norm_0.leaky_relu(0.2).unwrap();

    let conv_1 = lrelu.conv1d(&conv2_w, 1, 1, 1, 1).unwrap();
    let bias2 = conv2_b.reshape([1, 16, 1]).unwrap();
    let conv_1 = conv_1.broadcast_add(&bias2).unwrap();

    let residual = norm_0.add(&conv_1).unwrap();

    let log_mag = residual.narrow(1, 0, 8).unwrap();
    let magnitude = log_mag.exp().unwrap();

    let phase_raw = residual.narrow(1, 8, 8).unwrap();
    let phase = phase_raw.sin().unwrap();

    let cpu_output = nn_core::DynTensor::cat(&[&magnitude, &phase], 1).unwrap();
    let cpu_vals = cpu_output.to_flat_vec::<f32>().unwrap();

    // --- Numerical comparison ---

    assert_eq!(
        gpu_vals.len(),
        cpu_vals.len(),
        "output length mismatch: GPU={} vs CPU={}",
        gpu_vals.len(),
        cpu_vals.len()
    );

    let gpu_all_finite = gpu_vals.iter().all(|v| v.is_finite());
    let cpu_all_finite = cpu_vals.iter().all(|v| v.is_finite());
    assert!(gpu_all_finite, "GPU output contains non-finite values");
    assert!(cpu_all_finite, "CPU output contains non-finite values");

    let cos_sim = cosine_similarity(&gpu_vals, &cpu_vals);
    let max_diff = max_abs_diff(&gpu_vals, &cpu_vals);

    eprintln!("Varied-weights parity: cosine_similarity={cos_sim:.6}, max_abs_diff={max_diff:.6e}");
    eprintln!(
        "  GPU: {} elements, shape={:?}",
        gpu_vals.len(),
        gpu_output.dims()
    );
    eprintln!(
        "  CPU: {} elements, shape={:?}",
        cpu_vals.len(),
        cpu_output.dims()
    );

    assert!(
        cos_sim > 0.99,
        "cosine similarity {cos_sim:.6} below 0.99 threshold \
         (varied weights: auto-converted GPU vs hand-built CPU)"
    );
    assert!(
        max_diff < 0.5,
        "max absolute difference {max_diff:.6e} exceeds 0.5 threshold \
         (varied weights: auto-converted GPU vs hand-built CPU)"
    );

    eprintln!(
        "Mini decoder varied-weights parity: cos={cos_sim:.6}, max_diff={max_diff:.6e}, \
         {} steps, {} dispatches -- PASSED",
        compiled.num_steps(),
        compiled.num_dispatches(),
    );
}

