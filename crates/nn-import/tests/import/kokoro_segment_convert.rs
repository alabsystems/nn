/// Import PlBert segment and validate structure.
///
/// PlBert is a standard ALBERT encoder (12 shared layers) followed by a
/// Linear(768, 512) projection + transpose. Expected ops: Embedding, Linear,
/// LayerNorm, SDPA/MatMul, GELU, Add, Transpose, Reshape.
///
/// Inputs: input_ids [B,T], position_ids [T], token_type_ids [T] (3 inputs).
/// Output: bert_features [B, 512, T] (1 output).
#[test]
fn test_plbert_import() {
    let imported = match import_and_validate("plbert", 1, 1) {
        Some(g) => g,
        None => return,
    };

    // PlBert has at least 3 inputs (input_ids, position_ids, token_type_ids).
    // The actual count depends on how torch.export handles the attention_mask.
    assert!(
        imported.num_user_inputs >= 1,
        "PlBert should have >= 1 user input, got {}",
        imported.num_user_inputs
    );

    // Validate input names look reasonable (should reference ids/embeddings).
    for name in &imported.user_input_names {
        eprintln!("  PlBert input: '{name}'");
    }

    eprintln!("PlBert import: PASSED");
}

