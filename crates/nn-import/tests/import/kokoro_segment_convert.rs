/// Import the decoder segment and validate structure.
///
/// The decoder is already exported at `models/kokoro-82m/decoder/`.
/// This test mirrors `kokoro_decoder_import.rs` but is included here
/// so all 5 segments are tested in one file.
///
/// Inputs: x [B, 512, T], style [B, 128], har_source [B, 2*n_bins, T_stft] (3 inputs).
/// Outputs: magnitude [B, n_bins, T_out], phase [B, n_bins, T_out] (2 outputs).
#[test]
fn test_decoder_import() {
    let imported = match import_and_validate("decoder", 3, 2) {
        Some(g) => g,
        None => return,
    };

    use nn_core::dyn_tensor::trace::TraceOp;
    let nodes = imported.graph.nodes();

    // Decoder: 3 inputs (x, s, har), 2 outputs (spec, phase).
    assert_eq!(
        imported.num_user_inputs, 3,
        "decoder has 3 inputs (x, style, har_source)"
    );
    assert_eq!(
        imported.output_names.len(),
        2,
        "decoder has 2 outputs (magnitude, phase)"
    );

    // Conv1d: >= 40 (noise_convs + resblock convs + conv_post).
    let conv1d = nodes
        .iter()
        .filter(|n| matches!(n.op(), TraceOp::Conv1d { .. }))
        .count();
    assert!(conv1d >= 40, "expected >= 40 Conv1d ops, got {conv1d}");

    // ConvTranspose1d: 2 upsample layers.
    let conv_t = nodes
        .iter()
        .filter(|n| matches!(n.op(), TraceOp::ConvTranspose1d { .. }))
        .count();
    assert_eq!(
        conv_t, 2,
        "expected 2 ConvTranspose1d (2 upsampling stages)"
    );

    // InstanceNorm: >= 40 from AdaIN1d blocks.
    let instnorm = nodes
        .iter()
        .filter(|n| matches!(n.op(), TraceOp::InstanceNorm { .. }))
        .count();
    assert!(
        instnorm >= 40,
        "expected >= 40 InstanceNorm ops (AdaIN), got {instnorm}"
    );

    eprintln!("Decoder import: PASSED");
}

