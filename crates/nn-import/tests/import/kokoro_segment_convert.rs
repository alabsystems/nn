/// Import TextEncoder segment and validate structure.
///
/// TextEncoder: Embedding(178, 512) + 3x Conv1d(512, 512, k=5) + BiLSTM(512, 256)
///   + Linear(512, 512). Expected ops: Embedding, Conv1d, LayerNorm, LeakyReLU,
///   LSTM, Linear, Transpose, Permute.
///
/// Input: input_ids [B, T] (1 user input, possibly more for lengths/mask).
/// Output: text_features [B, 512, T] (1 output).
#[test]
fn test_text_encoder_import() {
    let imported = match import_and_validate("text_encoder", 1, 1) {
        Some(g) => g,
        None => return,
    };

    use nn_core::dyn_tensor::trace::TraceOp;
    let nodes = imported.graph.nodes();

    // TextEncoder should have Conv1d ops (3 convolution layers).
    let conv1d_count = nodes
        .iter()
        .filter(|n| matches!(n.op(), TraceOp::Conv1d { .. }))
        .count();
    eprintln!("  TextEncoder Conv1d count: {conv1d_count}");

    // TextEncoder has a BiLSTM which may appear as LSTM or decomposed ops.
    // Check for either LSTM or the typical decomposed pattern (many Linear ops).
    let linear_count = nodes
        .iter()
        .filter(|n| matches!(n.op(), TraceOp::Linear { .. }))
        .count();
    eprintln!("  TextEncoder Linear count: {linear_count}");

    eprintln!("TextEncoder import: PASSED");
}

