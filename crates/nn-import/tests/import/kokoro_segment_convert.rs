//! Integration tests for Kokoro segment export and import.
//!
//! Validates that each of the 5 Kokoro pipeline segments can be imported
//! via `import_model()` from torch.export `graph.json` + `weights.safetensors`.
//!
//! Segment layout (from designs/2026-03-29-kokoro-segment-export.md):
//!
//! - **PlBert** (Segment 0): ALBERT encoder + bert_encoder Linear.
//!   Inputs: input_ids [B,T], position_ids [T], token_type_ids [T].
//!   Output: bert_features [B, 512, T].
//!
//! - **TextEncoder** (Segment 1): Embedding + Conv1d + BiLSTM + Linear.
//!   Input: input_ids [B, T].
//!   Output: text_features [B, 512, T].
//!
//! - **ProsodyPredictor** (Segment 2): DurationEncoder (4x BiLSTM + AdaLayerNorm) + proj.
//!   Inputs: bert_features [B, 512, T], style [B, 128].
//!   Outputs: dur_logits [B, T, 50], features [B, 640, T].
//!
//! - **F0EnergyPredictor** (Segment 3): Shared BiLSTM + F0/Energy heads (AdainResBlk1d).
//!   Inputs: aligned_dur [B, 640, T_mel], style [B, 128].
//!   Outputs: f0 [B, 1, 2*T_mel], energy [B, 1, 2*T_mel].
//!
//! - **Decoder** (Segment 4): AdaIN ResBlks + ISTFTNet generator. Already exported.
//!   Inputs: x [B, 512, T], style [B, 128], har_source [B, 2*n_bins, T_stft].
//!   Outputs: magnitude [B, n_bins, T_out], phase [B, n_bins, T_out].
//!
//! Tests skip gracefully when model files are not present (they must be
//! generated by `crates/nn-import/python/export_kokoro_segments.py`).

// Tests are cfg-gated; helpers may appear unused without features.
#![allow(dead_code)]

use std::path::{Path, PathBuf};

use nn_import::import_model;

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .to_path_buf()
}

fn segment_dir(segment: &str) -> PathBuf {
    workspace_root()
        .join("models")
        .join("kokoro-82m")
        .join(segment)
}

/// Returns `true` if `graph.json` and `weights.safetensors` exist for a segment.
/// Prints a skip message and returns `false` otherwise.
fn require_segment_files(segment: &str) -> Option<(PathBuf, PathBuf)> {
    let dir = segment_dir(segment);
    let graph = dir.join("graph.json");
    let weights = dir.join("weights.safetensors");

    if !graph.exists() || !weights.exists() {
        eprintln!(
            "SKIP: Kokoro segment '{}' model files not found at {}",
            segment,
            dir.display()
        );
        return None;
    }
    Some((graph, weights))
}

/// Import a segment and run basic structural assertions.
fn import_and_validate(
    segment: &str,
    expected_min_inputs: usize,
    expected_min_outputs: usize,
) -> Option<nn_import::ImportedGraph> {
    let (graph_path, weights_path) = require_segment_files(segment)?;

    let imported = import_model(&graph_path, &weights_path)
        .unwrap_or_else(|e| panic!("import_model failed for segment '{segment}': {e:?}"));

    let node_count = imported.graph.nodes().len();
    assert!(
        node_count > 0,
        "segment '{segment}': expected > 0 nodes, got 0"
    );

    assert!(
        imported.num_user_inputs >= expected_min_inputs,
        "segment '{}': expected >= {} user inputs, got {}",
        segment,
        expected_min_inputs,
        imported.num_user_inputs
    );

    assert!(
        imported.output_names.len() >= expected_min_outputs,
        "segment '{}': expected >= {} outputs, got {}",
        segment,
        expected_min_outputs,
        imported.output_names.len()
    );

    eprintln!(
        "Kokoro segment '{}': {} nodes, {} user inputs {:?}, {} outputs {:?}",
        segment,
        node_count,
        imported.num_user_inputs,
        imported.user_input_names,
        imported.output_names.len(),
        imported.output_names
    );

    Some(imported)
}

