/// L3: Reference parity for PlBert segment.
#[test]
#[cfg(all(feature = "metal", feature = "reftest", target_os = "macos"))]
fn test_plbert_reference_parity() {
    let dir = segment_dir("plbert");
    let graph = dir.join("graph.json");
    let weights = dir.join("weights.safetensors");
    let reference = dir.join("reference.safetensors");

    if !graph.exists() || !weights.exists() || !reference.exists() {
        eprintln!(
            "SKIP: PlBert L3 parity — model or reference files not found at {}",
            dir.display()
        );
        return;
    }

    let _ = nn_metal::MetalBackend::init();
    nn_metal::register_metal_dyn_backend();
    let cache = nn_metal::PipelineCache::new(
        nn_metal::MetalContext::new().expect("Metal device required"),
    );

    let result = nn_import::convert(&graph, &weights, Some(&reference), &cache)
        .unwrap_or_else(|e| panic!("convert() failed for plbert: {e:?}"));

    let parity = result
        .proof
        .reference_parity
        .expect("reference parity should be available");
    assert!(
        parity.divergence.all_passed,
        "PlBert L3 parity failed: {:?}",
        parity.divergence
    );
    eprintln!("PlBert L3: reference parity PASSED");
}

